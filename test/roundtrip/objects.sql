CREATE INDEX ts_tbl_a_idx ON ts_tbl (a) TABLESPACE "Fast Space" WHERE a > 0;
CREATE INDEX ts_tbl_b_idx ON ts_tbl (b) TABLESPACE "Fast Space";
ALTER TABLE ts_tbl ADD CONSTRAINT ts_tbl_pkey PRIMARY KEY (b) USING INDEX TABLESPACE "Fast Space";
ALTER TABLE ts_tbl ADD CONSTRAINT ts_tbl_excl EXCLUDE USING gist (c WITH &&) USING INDEX TABLESPACE "Fast Space" WHERE (a > 10);
