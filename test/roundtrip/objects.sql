  x bigint DEFAULT nextval('shared_seq'::regclass),
  "Serial Col" serial,
  UNIQUE ("select", x) DEFERRABLE
);
CREATE UNIQUE INDEX weird_replident ON "Mixed Case"."Weird Table" ("Id");
ALTER TABLE "Mixed Case"."Weird Table" ALTER COLUMN "Id" SET NOT NULL;
ALTER TABLE "Mixed Case"."Weird Table" REPLICA IDENTITY USING INDEX weird_replident;

-- Partitioning: range, sub-partitioning, list, default, hash, a foreign partition.
CREATE TABLE measurements (
  id bigint NOT NULL,
  logdate date NOT NULL,
  region text,
  val integer DEFAULT 0,
  PRIMARY KEY (id, logdate)
) PARTITION BY RANGE (logdate);
CREATE INDEX measurements_region_idx ON measurements (region);
CREATE TABLE measurements_2024 PARTITION OF measurements FOR VALUES FROM ('2024-01-01') TO ('2025-01-01');
CREATE TABLE measurements_2025 PARTITION OF measurements FOR VALUES FROM ('2025-01-01') TO ('2026-01-01') PARTITION BY RANGE (logdate);
CREATE TABLE measurements_2025_h1 PARTITION OF measurements_2025 FOR VALUES FROM ('2025-01-01') TO ('2025-07-01');
CREATE TABLE regions (code text, name text) PARTITION BY LIST (code);
CREATE TABLE regions_eu PARTITION OF regions FOR VALUES IN ('eu', 'uk', 'it''s');
CREATE TABLE measurements_def PARTITION OF measurements DEFAULT;
CREATE INDEX measurements_2024_val_idx ON measurements_2024 (val);
ALTER TABLE measurements_def ALTER COLUMN val SET DEFAULT 42;
ALTER TABLE measurements_def ALTER COLUMN region SET NOT NULL;
COMMENT ON COLUMN measurements_2024.val IS 'partition comment';

CREATE TABLE hashed (id integer, data text) PARTITION BY HASH (id);
CREATE TABLE hashed_0 PARTITION OF hashed FOR VALUES WITH (MODULUS 2, REMAINDER 0);
CREATE FOREIGN TABLE hashed_1 PARTITION OF hashed FOR VALUES WITH (MODULUS 2, REMAINDER 1)
  SERVER file_srv OPTIONS (filename '/dev/null');
ALTER FOREIGN TABLE hashed_1 ALTER COLUMN data OPTIONS (force_null 'true');

-- Partitioned table with a foreign key: the partitions inherit it.
CREATE TABLE events (id integer NOT NULL, customer_id integer REFERENCES app.customers (id), at date NOT NULL)
  PARTITION BY RANGE (at);
CREATE TABLE events_2024 PARTITION OF events FOR VALUES FROM ('2024-01-01') TO ('2025-01-01');
CREATE TRIGGER events_trg AFTER INSERT ON events FOR EACH ROW EXECUTE FUNCTION trg_fn();

-- Inheritance.
CREATE TABLE cities (name text NOT NULL, population real, CONSTRAINT pop_check CHECK (population >= 0));
CREATE TABLE capitals (state char(2) DEFAULT 'XX') INHERITS (cities);
CREATE TABLE towns (mayor text) INHERITS (cities, app.audit_log);

-- Typed table.
CREATE TABLE people OF person_t (PRIMARY KEY (name), age WITH OPTIONS DEFAULT 0 NOT NULL);

-- Unlogged table with a self-referencing foreign key.
CREATE UNLOGGED TABLE cache_tbl (k text PRIMARY KEY, v text, expires timestamptz, parent text REFERENCES cache_tbl (k));

-- Table with no columns.
CREATE TABLE empty_tbl ();

