-- Views.
CREATE VIEW v_cust WITH (security_barrier = true) AS
  SELECT id, email FROM app.customers WHERE score > 0
  UNION ALL
  SELECT 0, 'none';
COMMENT ON COLUMN v_cust.email IS 'view column comment';
CREATE VIEW v_check AS SELECT order_id, qty FROM orders WHERE qty > 1 WITH LOCAL CHECK OPTION;
CREATE TRIGGER v_check_ins INSTEAD OF INSERT ON v_check FOR EACH ROW EXECUTE FUNCTION view_ins_fn();
CREATE MATERIALIZED VIEW mv_orders WITH (fillfactor = 90) AS
  SELECT customer_id, count(*) AS n, sum(price) AS total FROM orders GROUP BY customer_id;
CREATE UNIQUE INDEX mv_orders_customer ON mv_orders (customer_id);

