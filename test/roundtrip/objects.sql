-- Fixture relations (PostgreSQL 14+). Created in this order, which the round trip relies on:
-- a relation's statements may only refer to relations created before it.

CREATE TABLE app.audit_log (msg text);

-- Plain table with most column features, indexes, triggers, rules, policies and statistics.
CREATE TABLE app.customers (
  id serial PRIMARY KEY,
  email varchar(255) NOT NULL UNIQUE,
  name text COLLATE "C" DEFAULT 'anon'::text,
  "Display Name" text,
  "user" text,
  mood app.mood DEFAULT 'ok',
  score numeric(10,2) CHECK (score >= 0),
  tags text[] DEFAULT '{}',
  created timestamp(3) with time zone NOT NULL DEFAULT now(),
  doc jsonb,
  code char(3),
  b bytea COMPRESSION pglz,
  note text DEFAULT 'a | b',
  multi text DEFAULT E'line one\nline two',
  pos posint
) WITH (fillfactor = 80, autovacuum_enabled = false);
COMMENT ON COLUMN app.customers.email IS 'Customer''s email';
COMMENT ON COLUMN app.customers.name IS 'multi
line comment';
ALTER TABLE app.customers ALTER COLUMN name SET STATISTICS 500;
ALTER TABLE app.customers ALTER COLUMN doc SET STORAGE EXTERNAL;
ALTER TABLE app.customers ALTER COLUMN score SET STORAGE EXTENDED;
CREATE INDEX customers_lower_name_idx ON app.customers (lower(name));
CREATE INDEX customers_created_partial ON app.customers (created DESC NULLS LAST) WHERE score > 10;
CREATE UNIQUE INDEX customers_code_uidx ON app.customers (code) INCLUDE (name) WITH (fillfactor = 70);
CREATE INDEX customers_doc_gin ON app.customers USING gin (doc jsonb_path_ops);
CREATE INDEX "Customers Mixed" ON app.customers ("Display Name" text_pattern_ops);
CLUSTER app.customers USING customers_pkey;
CREATE STATISTICS app.cust_stats (ndistinct, dependencies) ON email, name FROM app.customers;
CREATE STATISTICS app.cust_stats_all ON email, code FROM app.customers;
ALTER STATISTICS app.cust_stats_all SET STATISTICS 50;
CREATE TRIGGER cust_trg BEFORE INSERT OR UPDATE ON app.customers FOR EACH ROW EXECUTE FUNCTION trg_fn();
CREATE TRIGGER cust_trg_dis AFTER DELETE ON app.customers FOR EACH ROW WHEN (OLD.id > 0) EXECUTE FUNCTION trg_fn();
ALTER TABLE app.customers DISABLE TRIGGER cust_trg_dis;
CREATE TRIGGER cust_trg_always AFTER UPDATE OF email ON app.customers FOR EACH STATEMENT EXECUTE FUNCTION trg_fn();
ALTER TABLE app.customers ENABLE ALWAYS TRIGGER cust_trg_always;
CREATE TRIGGER cust_trg_replica AFTER TRUNCATE ON app.customers EXECUTE FUNCTION trg_fn();
ALTER TABLE app.customers ENABLE REPLICA TRIGGER cust_trg_replica;
CREATE CONSTRAINT TRIGGER cust_ctrg AFTER INSERT ON app.customers DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION trg_fn();
ALTER TABLE app.customers ENABLE ROW LEVEL SECURITY;
CREATE POLICY p_sel ON app.customers FOR SELECT TO alice, "Bob" USING (score > 0);
CREATE POLICY p_all ON app.customers AS RESTRICTIVE USING (true) WITH CHECK (email <> '');
CREATE POLICY "P Update" ON app.customers FOR UPDATE USING (CASE WHEN score > 5 THEN true ELSE false END);
CREATE RULE cust_rule AS ON DELETE TO app.customers WHERE OLD.id < 0 DO INSTEAD NOTHING;
CREATE RULE cust_rule_dis AS ON UPDATE TO app.customers WHERE OLD.id < -10 DO ALSO INSERT INTO app.audit_log VALUES ('updated');
ALTER TABLE app.customers DISABLE RULE cust_rule_dis;
ALTER PUBLICATION pub1 ADD TABLE app.customers;

-- Identity, generated columns, deferrable primary key, exclusion constraint, foreign keys.
CREATE TABLE orders (
  order_id bigint GENERATED ALWAYS AS IDENTITY,
  customer_id integer NOT NULL REFERENCES app.customers (id) ON DELETE CASCADE,
  qty integer NOT NULL DEFAULT 1,
  price numeric NOT NULL,
  total numeric GENERATED ALWAYS AS (qty * price) STORED,
  during tstzrange,
  referrer_id integer,
  CONSTRAINT orders_pkey PRIMARY KEY (order_id) DEFERRABLE INITIALLY DEFERRED,
  CONSTRAINT orders_qty_check CHECK (qty > 0) NO INHERIT,
  CONSTRAINT orders_case_check CHECK (CASE WHEN qty > 10 THEN price < 100::numeric ELSE true END),
  CONSTRAINT no_overlap EXCLUDE USING gist (customer_id WITH =, during WITH &&),
  CONSTRAINT orders_referrer_fk FOREIGN KEY (referrer_id) REFERENCES app.customers (id) MATCH FULL ON UPDATE SET NULL
);
ALTER TABLE orders ADD CONSTRAINT price_pos CHECK (price > 0) NOT VALID;
ALTER TABLE orders REPLICA IDENTITY FULL;

-- Names that need quoting, a shared sequence, an identity column by default.
CREATE TABLE "Mixed Case"."Weird Table" (
